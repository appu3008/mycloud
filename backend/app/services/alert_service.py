"""Quota alerts: evaluate live usage against the per-user threshold.

Alerts are real Notifications generated by actual usage changes (upload
completion, file replacement), never periodic fake warnings. One unread
warning per user is kept at a time; dismissing it allows a new one when the
threshold is still crossed.
"""

from __future__ import annotations

import json

from sqlalchemy.orm import Session as SAMSession

from ..core.config import get_settings
from ..models import Notification, StorageQuota, new_id, utcnow
from . import upload_service

ALERT_TYPE = "quota_warning"


def threshold_pct(db: SAMSession, user_id: str) -> int:
    row = db.get(StorageQuota, user_id)
    return int(row.notify_threshold_pct) if row else 85


def evaluate_quota(db: SAMSession, *, user_id: str) -> Notification | None:
    used = upload_service.active_usage_bytes(db, user_id)
    quota = upload_service._quota_bytes(db, get_settings(), user_id)
    pct = int(used / quota * 100) if quota else 0
    threshold = threshold_pct(db, user_id)
    if pct < threshold:
        return None
    # Avoid spamming: keep a single unread warning until it is dismissed.
    unread = db.query(Notification).filter(
        Notification.user_id == user_id,
        Notification.type == ALERT_TYPE,
        Notification.is_read.is_(False),
    ).first()
    if unread:
        return None
    alert = Notification(
        id=new_id(),
        user_id=user_id,
        type=ALERT_TYPE,
        payload=json.dumps(
            {"used_bytes": int(used), "quota_bytes": quota, "percent": pct,
             "threshold": threshold}
        ),
        is_read=False,
        created_at=utcnow(),
    )
    db.add(alert)
    return alert


def alert_status(db: SAMSession, *, user_id: str) -> dict:
    from .analytics_service import storage_usage

    usage = storage_usage(db, user_id=user_id)
    used, quota = usage["used_bytes"], usage["quota_bytes"]
    pct = int(used / quota * 100) if quota else 0
    notes = (
        db.query(Notification)
        .filter(Notification.user_id == user_id)
        .order_by(Notification.created_at.desc())
        .limit(50)
        .all()
    )
    return {
        "used_bytes": used,
        "quota_bytes": quota,
        "percent": pct,
        "threshold": threshold_pct(db, user_id),
        "triggered": pct >= threshold_pct(db, user_id),
        "notifications": [
            {
                "id": row.id,
                "type": row.type,
                "payload": json.loads(row.payload),
                "is_read": row.is_read,
                "created_at": row.created_at,
            }
            for row in notes
        ],
    }


def dismiss(db: SAMSession, *, user_id: str, notification_id: str) -> bool:
    row = db.get(Notification, notification_id)
    if row is None or row.user_id != user_id:
        return False
    row.is_read = True
    return True
