"""Hosting app manager: validate apps, stage nginx config, manage static files.

Nothing here writes to /etc/nginx or reloads services: the generated config
and the apply script are staged in a user-owned directory for operator review.
That keeps privileged actions explicit (and works without passwordless sudo).
"""

from __future__ import annotations

import re
from pathlib import Path

from fastapi import HTTPException, status
from sqlalchemy import select
from sqlalchemy.orm import Session as SAMSession

from ..core.config import Settings
from ..models import HostedApp, new_id, utcnow

_NAME = re.compile(r"^[a-z0-9][a-z0-9-]{0,62}$")
_DOMAIN = re.compile(r"^[a-zA-Z0-9.-]{1,255}$")
AUTO_PORT = 8100


def _validate(
    db: SAMSession,
    *,
    name: str,
    kind: str,
    domain: str,
    path_prefix: str,
    upstream_port: int | None,
    exclude_id: str | None = None,
) -> None:
    if not _NAME.match(name):
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail={"error": "invalid_app_name"})
    if kind not in {"static", "proxy"}:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail={"error": "invalid_app_kind"})
    if not _DOMAIN.match(domain) or ".." in domain:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail={"error": "invalid_domain"})
    if path_prefix != "/" and (
        not path_prefix.startswith("/") or ".." in path_prefix or "//" in path_prefix
    ):
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail={"error": "invalid_path_prefix"})
    if kind == "proxy" and (upstream_port is None or not 1 <= upstream_port <= 65535):
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail={"error": "invalid_upstream_port"})
    for row in db.execute(select(HostedApp)).scalars().all():
        if row.id == exclude_id:
            continue
        if row.name == name:
            raise HTTPException(status.HTTP_409_CONFLICT, detail={"error": "app_name_exists"})
        if row.domain == domain and row.path_prefix.rstrip("/") == path_prefix.rstrip("/"):
            raise HTTPException(status.HTTP_409_CONFLICT, detail={"error": "route_exists"})
        if upstream_port and row.upstream_port == upstream_port:
            raise HTTPException(status.HTTP_409_CONFLICT, detail={"error": "port_in_use"})


def create_app(
    db: SAMSession,
    *,
    name: str,
    kind: str,
    domain: str,
    path_prefix: str,
    upstream_port: int | None,
    description: str = "",
    settings: Settings,
) -> HostedApp:
    if upstream_port is None and kind == "proxy":
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail={"error": "invalid_upstream_port"})
    _validate(
        db, name=name, kind=kind, domain=domain,
        path_prefix=path_prefix, upstream_port=upstream_port,
    )
    root_path = None
    if kind == "static":
        root_path = str(settings.data_dir / "hosting" / name)
        Path(root_path).mkdir(parents=True, exist_ok=True)
    app = HostedApp(
        id=new_id(), name=name, kind=kind, domain=domain,
        path_prefix=path_prefix, upstream_port=upstream_port,
        root_path=root_path, enabled=True, description=description[:512],
        created_at=utcnow(), updated_at=utcnow(),
    )
    db.add(app)
    return app


def owned_app(db: SAMSession, app_id: str) -> HostedApp:
    app = db.get(HostedApp, app_id)
    if app is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail={"error": "app_not_found"})
    return app


def update_app(
    db: SAMSession, app_id: str, *, enabled: bool | None, description: str | None
) -> HostedApp:
    app = owned_app(db, app_id)
    if enabled is not None:
        app.enabled = enabled
    if description is not None:
        app.description = description[:512]
    app.updated_at = utcnow()
    return app


def delete_app(db: SAMSession, app_id: str) -> dict:
    app = owned_app(db, app_id)
    db.delete(app)
    return {"deleted": app_id}


def app_dict(app: HostedApp) -> dict:
    return {
        "id": app.id,
        "name": app.name,
        "kind": app.kind,
        "domain": app.domain,
        "path_prefix": app.path_prefix,
        "upstream_port": app.upstream_port,
        "root_path": app.root_path,
        "enabled": app.enabled,
        "description": app.description,
        "created_at": app.created_at,
    }


def list_apps(db: SAMSession) -> list[dict]:
    rows = db.execute(select(HostedApp).order_by(HostedApp.name.asc())).scalars().all()
    return [app_dict(row) for row in rows]


def generate_config(db: SAMSession) -> str:
    """Idempotent nginx snippet for all enabled apps."""
    blocks = [
        "# Generated by MyCloud app manager — review before installing.",
        "# Install (requires sudo): see deployment/apply-hosting.sh.example",
        "",
    ]
    apps = [row for row in db.execute(select(HostedApp)).scalars().all() if row.enabled]
    if not apps:
        blocks.append("# No apps enabled yet.")
        return "\n".join(blocks) + "\n"
    for app in apps:
        location = app.path_prefix.rstrip("/") or "/"
        blocks.extend(
            [
                f"# app: {app.name} ({app.kind})",
                "server {",
                "    listen 80;",
                f"    server_name {app.domain};",
                "",
                f"    location {location} {{",
            ]
        )
        if app.kind == "static":
            blocks.append(f"        root {app.root_path};")
            blocks.append("        try_files $uri $uri/ =404;")
        else:
            blocks.append(f"        proxy_pass http://127.0.0.1:{app.upstream_port};")
            blocks.append("        proxy_set_header Host $host;")
            blocks.append("        proxy_set_header X-Real-IP $remote_addr;")
            blocks.append("        proxy_http_version 1.1;")
        blocks.extend(["    }", "}", ""])
    return "\n".join(blocks) + "\n"


def stage_config(db: SAMSession, settings: Settings) -> dict:
    """Write config + apply script into a user-owned staging directory."""
    target_dir = settings.data_dir / "hosting" / "staged"
    target_dir.mkdir(parents=True, exist_ok=True)
    config = generate_config(db)
    config_path = target_dir / "mycloud-apps.conf"
    config_path.write_text(config, encoding="utf-8")
    script_path = target_dir / "apply.sh"
    script_path.write_text(
        "#!/usr/bin/env sh\n"
        "set -eu\n"
        f"sudo install -m 0644 {config_path} /etc/nginx/sites-available/mycloud-apps.conf\n"
        "sudo ln -sf /etc/nginx/sites-available/mycloud-apps.conf "
        "/etc/nginx/sites-enabled/mycloud-apps.conf\n"
        "sudo nginx -t && sudo systemctl reload nginx\n",
        encoding="utf-8",
    )
    script_path.chmod(0o755)
    return {
        "config_path": str(config_path),
        "apply_script": str(script_path),
        "config": config,
        "note": "Config staged only. Run the apply script yourself with sudo "
                "(no privileged action was taken by the server).",
    }


def _safe_root(app: HostedApp) -> Path:
    if not app.root_path or app.kind != "static":
        raise HTTPException(status.HTTP_409_CONFLICT, detail={"error": "not_a_static_app"})
    return Path(app.root_path).resolve()


def list_static_files(db: SAMSession, app_id: str) -> list[dict]:
    app = owned_app(db, app_id)
    root = _safe_root(app)
    files = []
    for path in sorted(root.rglob("*")):
        if path.is_file() and path.resolve().is_relative_to(root):
            files.append(
                {
                    "path": str(path.relative_to(root)),
                    "size_bytes": path.stat().st_size,
                }
            )
    return files


def write_static_file(db: SAMSession, app_id: str, relative_path: str, content: str) -> dict:
    app = owned_app(db, app_id)
    root = _safe_root(app)
    candidate = (root / relative_path).resolve()
    if not candidate.is_relative_to(root) or candidate == root:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail={"error": "invalid_file_path"})
    current_size = candidate.stat().st_size if candidate.exists() else 0
    if current_size > 1024 * 1024:
        raise HTTPException(status.HTTP_413_REQUEST_ENTITY_TOO_LARGE, detail={"error": "file_too_large"})
    candidate.parent.mkdir(parents=True, exist_ok=True)
    candidate.write_text(content, encoding="utf-8")
    return {"path": relative_path, "size_bytes": candidate.stat().st_size}
